export const calculateBmi = (weightKg: number, heightCm: number): { bmi: number; classification: string; color: string } => {
  if (!heightCm || heightCm <= 0 || !weightKg || weightKg <= 0) {
    return { bmi: 0, classification: 'Chưa xác định', color: 'text-gray-500' };
  }
  const heightM = heightCm / 100;
  const bmi = Number((weightKg / (heightM * heightM)).toFixed(1));
  
  // Theo chuẩn WHO Châu Á (IDI & WPRO)
  if (bmi < 18.5) return { bmi, classification: 'Thiếu cân (Gầy)', color: 'text-amber-500' };
  if (bmi < 23) return { bmi, classification: 'Bình thường (Lý tưởng)', color: 'text-emerald-500' };
  if (bmi < 25) return { bmi, classification: 'Thừa cân (Tiền béo phì)', color: 'text-yellow-600' };
  if (bmi < 30) return { bmi, classification: 'Béo phì độ I', color: 'text-orange-500' };
  return { bmi, classification: 'Béo phì độ II (Nguy hiểm)', color: 'text-red-500' };
};

